<?php

declare(strict_types=1);

namespace Theme\Helpers;

final class Text
{
    public static function cityPrepositional(string $city): string
    {
        $dictionary = [
            'Москва' => 'Москве',
            'Санкт-Петербург' => 'Санкт-Петербурге',
            'Казань' => 'Казани',
            'Пермь' => 'Перми',
            'Тверь' => 'Твери',
            'Тюмень' => 'Тюмени',
            'Рязань' => 'Рязани',
            'Астрахань' => 'Астрахани',
            'Ставрополь' => 'Ставрополе',
            'Ярославль' => 'Ярославле',
            'Нижний Новгород' => 'Нижнем Новгороде',
            'Нижний Тагил' => 'Нижнем Тагиле',
            'Ростов-на-Дону' => 'Ростове-на-Дону',
            'Набережные Челны' => 'Набережных Челнах',
            'Чебоксары' => 'Чебоксарах',
            'Сочи' => 'Сочи',
            'Тольятти' => 'Тольятти',
            'Иваново' => 'Иваново',
            'Кемерово' => 'Кемерово',
            'Самара' => 'Самаре',
            'Уфа' => 'Уфе',
            'Тула' => 'Туле',
            'Пенза' => 'Пензе',
            'Махачкала' => 'Махачкале',
        ];

        if (isset($dictionary[$city])) {
            return $dictionary[$city];
        }

        $last = mb_substr($city, -1, 1, 'UTF-8');

        if ($last === 'а' || $last === 'я' || $last === 'ь') {
            return mb_substr($city, 0, -1, 'UTF-8') . 'е';
        }

        if (in_array($last, ['о', 'е', 'и', 'ы'], true)) {
            return $city;
        }

        return $city . 'е';
    }
}
